/**
 * 无工具调用尾注
 */
const NO_TOOLS_TRAILER =
  '\n\n提醒：不要调用未知工具。仅以纯文本回应——' +
  '一个 <analysis> 块后接一个 <summary> 块。' +
  '工具调用将被拒绝，你将失败。';

/**
 * 获取部分压缩提示词
 *
 * @param customInstructions 自定义压缩指令
 * @param direction 压缩方向
 * @returns 完整的部分压缩提示词
 */
export function getPartialCompactPrompt(
  customInstructions?: string,
  direction: 'from' | 'up_to' = 'from'
): string {
  const template =
    direction === 'up_to'
      ? PARTIAL_COMPACT_UP_TO_PROMPT
      : PARTIAL_COMPACT_PROMPT;
  let prompt = NO_TOOLS_PREAMBLE + template;

  if (customInstructions && customInstructions.trim() !== '') {
    prompt += `\n\n附加指令：\n${customInstructions}`;
  }

  prompt += NO_TOOLS_TRAILER;

  return prompt;
}

/**
 * 获取完整压缩提示词
 *
 * @param customInstructions 自定义压缩指令
 * @returns 完整的压缩提示词
 */
export function getCompactPrompt(customInstructions?: string): string {
  let prompt = NO_TOOLS_PREAMBLE + BASE_COMPACT_PROMPT;

  if (customInstructions && customInstructions.trim() !== '') {
    prompt += `\n\n附加指令：\n${customInstructions}`;
  }

  prompt += NO_TOOLS_TRAILER;

  return prompt;
}

/**
 * 获取压缩摘要的用户消息内容
 * 将模型返回的摘要包装成可插入对话的用户消息
 *
 * @param summary 模型返回的摘要文本
 * @param transcriptPath 对话记录路径
 * @returns 包装后的用户消息内容
 */
export function getCompactUserSummaryMessage(
  summary: string,
  transcriptPath?: string
): string {
  let message = `[之前的对话已摘要]\n\n${summary}`;

  if (transcriptPath) {
    message += `\n\n<previous_conversation_transcript_path>${transcriptPath}</previous_conversation_transcript_path>`;
  }

  return message;
}
