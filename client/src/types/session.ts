/** 工作模式：plan（计划）/ do（执行） */
export type WorkMode = "plan" | "do";

/**
 * B1（2026-11-09）：会话自主度。
 * - `interactive`（缺省）：既有逐轮交互；
 * - `demand`：许愿式 —— 用户只给目标，自动规划/执行/验收/交付。
 * 事实来源为后端 `metadata.autonomy`（缺省/脏值 ⇒ 视为 `interactive`）。
 */
export type AutonomyMode = "interactive" | "demand";

/**
 * PR-3（2026-10-23）：会话级审批模式。
 * - `ask`（默认）：所有需要审批的工具都人工确认；
 * - `auto-local`：只读 + **会话工作区内**的本地写自动执行（shell / 外部 / 越界写仍需审批）。
 */
export type ApprovalMode = "ask" | "auto-local";

/**
 * P1（2026-11-04）：会话级**权限模式**（第三层；覆盖进程默认档 `PERMISSION_MODE`）。
 *
 * 取值域与后端 `@openliri/infra/common` 的 `PERMISSION_MODES` **同集合**（9 档）：
 * 后端对非法值 400（`permission_mode must be one of …`）⇒ 漂移会显式报错，不静默降级。
 * `null` = 清除会话覆盖、跟随进程默认档。
 */
export type SessionPermissionMode =
  | "default"
  | "acceptEdits"
  | "plan"
  | "bypass"
  | "dontAsk"
  | "auto"
  | "ask"
  | "alwaysAsk"
  | "strict";

/**
 * 回复详略档（`/effort` 与输入区「回复设置」共用；源：会话 metadata.effortLevel）
 * `auto` = 不注入任何指令（与未设置等价）。
 */
export type ReplyEffortLevel = "low" | "medium" | "high" | "auto";

/**
 * #23（2026-10-30）：会话**持久化状态**（与后端 `DataSessionStatus` 10 态词表一致）。
 *
 * 来源：后端 `GET /v1/sessions`（`SessionInfo.status`，取自持久层 `UnifiedSession.status`）。
 * 此前该字段未上接口 ⇒ 前端无从区分「正常 / 已暂停 / 出错」会话。
 */
export type SessionStatus =
  | "active"
  | "paused"
  | "ended"
  | "archived"
  | "idle"
  | "running"
  | "requires_action"
  | "completed"
  | "error"
  | "aborted";

/**
 * P0-1（2026-11-05）：会话工作区状态（后端 `GET /v1/sessions/:id` 的 `workspaceStatus`）。
 *
 * - `unbound`：会话未绑定工作区（不是错误）；
 * - `ok`：全部根可用；
 * - `partial`：多根场景下部分根已失效；
 * - `invalid`：全部根已失效（典型：worktree 被清理后会话仍钉在旧根）。
 *
 * 取值与后端 `WorkspaceStatusState`（infra `toolContract/workspaceRoots`）同集合。
 */
export type WorkspaceStatusState = "unbound" | "ok" | "partial" | "invalid";

export interface WorkspaceStatus {
  state: WorkspaceStatusState;
  /** 会话当前的工作区根（首根 = 主工作区） */
  roots: string[];
  /** 已失效的根 */
  missingRoots: string[];
}

export interface Session {
  id: string;
  /** 会话持久化状态（缺省 = 后端未提供，按正常会话处理） */
  status?: SessionStatus;
  /** 会话的 Plan/Do 工作模式（源：metadata.workMode 展平） */
  workMode?: WorkMode;
  /** B1（2026-11-09）：会话自主度（源：metadata.autonomy 展平；缺省 === interactive） */
  autonomy?: AutonomyMode;
  /** PR-3：会话级审批模式（源：metadata.approvalMode 展平；缺省 ask） */
  approvalMode?: ApprovalMode;
  /**
   * P1（2026-11-04）：会话级权限模式（源：`metadata.permission_mode` 展平）。
   * 缺省/`null` ⇒ 跟随进程默认档（UI 显示「跟随默认」）。
   */
  permissionMode?: SessionPermissionMode;
  /** 会话的回复详略档（源：metadata.effortLevel 展平；未设置 ⇒ auto） */
  effortLevel?: ReplyEffortLevel;
  title: string;
  createdAt: string;
  updatedAt: string;
  messageCount: number;
  roundCount: number;
  agentId?: string;
  agentName?: string;
  source?: string;
  tokenUsage?: {
    totalInput: number;
    totalOutput: number;
  };
  /** 标记该会话标题是否已由 AI 自动生成或用户手动重命名 */
  titleAutoGenerated?: boolean;

  /** M1-T1.3（2026-08-31）：列表置顶标记（源：metadata.pinned 展平） */
  pinned?: boolean;

  /** ===== 会话绑定资源（用于会话级模型和工作空间管理） ===== */

  /** 该会话绑定的模型 ID（空表示使用全局默认模型） */
  modelId?: string;

  /** 该会话绑定的 Provider ID（与 modelId 配合使用） */
  providerId?: string;

  /** 该会话所属的工作空间 ID（空表示不属于任何工作空间） */
  workspaceId?: string;

  /**
   * N-64（2026-09-20）：该会话所属**项目 ID** —— 项目归属的**权威事实面**
   * （后端 `effectiveProjectId()` 即按 `metadata.projectId` 优先判定，legacy
   * `workspaceId` 的 `project-` 前缀仅作兜底）。
   */
  projectId?: string;

  /** 该会话绑定的工作空间物理路径 */
  workspacePath?: string;

  /**
   * P0-1（2026-11-05）：工作区状态（后端**详情接口**读时派生；列表接口不返回）。
   *
   * 真机背景：worktree 被清理后会话仍钉在旧根，此前只有首次工具调用才报
   * 「路径越界 / ENOENT」。`invalid` = 全部根已失效，`partial` = 多根场景部分失效。
   */
  workspaceStatus?: WorkspaceStatus;

  /** 该会话的任务分工覆盖（仅覆盖部分任务类型，未覆盖的走全局配置） */
  tasksOverride?: Partial<import("./model").TaskModelConfig>;

  /** ===== 运行时元数据 ===== */

  /** 会话元数据（后端 DataSessionMetadata 投影） */
  metadata?: {
    workMode?: WorkMode;
    /** B1（2026-11-09）：会话自主度（`demand` = 许愿式；缺省 === interactive） */
    autonomy?: AutonomyMode;
    /** PR-3：会话级审批模式（`auto-local` = 只读 + 工作区内本地写自动执行） */
    approvalMode?: ApprovalMode;
    /** P1（2026-11-04）：会话级权限模式（9 档；`null`/缺省 ⇒ 跟随进程默认档） */
    permission_mode?: SessionPermissionMode | null;
    roundCount?: number;
    rollbackCount?: number;
    isStreaming?: boolean;
    roundIndex?: Record<string, number>;
    roundCounter?: number;
    /** A1 临时对话：temporary 会话不入历史/记忆/FTS（持久化标记，CS02） */
    temporary?: boolean;
  };
}
