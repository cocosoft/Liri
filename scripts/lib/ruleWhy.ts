/** 取某条规则的「为什么是问题」；无精确条目则按规则族；都没有返回 `null` */
export function explainRule(ruleId: string): string | null {
  const exact = RULE_WHY_BY_ID[ruleId];
  if (exact) return exact;
  const family = RULE_WHY_BY_FAMILY.find(([pattern]) => pattern.test(ruleId));
  return family ? family[1] : null;
}
